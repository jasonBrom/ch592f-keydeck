void c5_features_init(void);
/* USB configured/awake; BLE encrypted/awake (independent of input CCCs).
 * Main context only. A disconnected source loses only its own host state. */
void c5_features_link_source(uint8_t source, bool ready);
void c5_features_link(bool usb_ready);
void c5_features_tick(uint32_t milliseconds);
/* HID payload only: transport owns the Report ID byte. GET is bounded RAM-only
 * and safe in USB IRQ; SET runs in the main loop (it can reach haptic I2C).
 * type 2 = Output, type 3 = Feature. false requests USB STALL.
 */
size_t c5_features_get(uint8_t report_id, uint8_t *out, size_t capacity);
bool c5_features_set(uint8_t report_type, uint8_t report_id,
                     const uint8_t *data, size_t length);
size_t c5_features_get_source(uint8_t source, uint8_t report_id,
                              uint8_t *out, size_t capacity);
bool c5_features_set_source(uint8_t source, uint8_t report_type,
                            uint8_t report_id, const uint8_t *data, size_t length);
/* GET snapshots one complete payload. For BLE long reads cache it at offset 0
 * and slice that cache for Read Blob: lamp-attribute GET advances its cursor.
 * SET validates the entire report before changing state; false must become an
 * ATT error/USB STALL. Legacy get/set/link functions target USB only.
 * Arbitration follows configuration transport preference, with USB priority in
 * auto mode. Inactive hosts may retain lamp/auto-haptic state, but manual haptic
 * output from an inactive source is rejected and cannot stop the active host. */
/* Call with final locally rendered colors immediately before the lights HAL.
 * Autonomous mode records them; host mode replaces them only while awake.
 * false forces black even if Windows retains LampArray ownership. Status LED
 * is separate; cached host colors remain available for a later idle wake.
 */
bool c5_features_lights(uint8_t rgb[15], bool awake);
void c5_features_auto_haptic(uint8_t local_strength);

